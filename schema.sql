-- ============================================================================
-- Основная таблица: Пользователи
-- ============================================================================
CREATE TABLE users (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    specialization_id       INTEGER NOT NULL,
    primary_specialty_id    INTEGER NULL,
    secondary_specialty_id  INTEGER NULL,
    practice_condition_id   INTEGER NULL,
    country                 VARCHAR(100) NOT NULL DEFAULT '',
    email                   VARCHAR(255) NOT NULL UNIQUE,
    password_hash           VARCHAR(255) NOT NULL,
    gender                  gender_type NOT NULL,
    birth_date              DATE NULL,
    work_start_year         SMALLINT NULL,
    first_name              VARCHAR(100) NOT NULL DEFAULT '',
    last_name               VARCHAR(100) NOT NULL DEFAULT '',
    middle_name             VARCHAR(100) NULL,
    phone                   VARCHAR(20) NULL,
    city                    VARCHAR(100) NULL,
    workplace               VARCHAR(255) NULL,
    utm_campaign            VARCHAR(255) NULL,
    utm_source              VARCHAR(255) NULL,
    cookie_id               VARCHAR(64) NULL,
    status                  user_status_type NOT NULL DEFAULT 'registered',
    registered_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ NULL,

    CONSTRAINT fk_users_specialization
        FOREIGN KEY (specialization_id) REFERENCES specializations (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_users_primary_specialty
        FOREIGN KEY (primary_specialty_id) REFERENCES medical_specialties (id)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_users_secondary_specialty
        FOREIGN KEY (secondary_specialty_id) REFERENCES medical_specialties (id)
        ON DELETE SET NULL ON UPDATE CASCADE,
    CONSTRAINT fk_users_practice_condition
        FOREIGN KEY (practice_condition_id) REFERENCES practice_conditions (id)
        ON DELETE SET NULL ON UPDATE CASCADE
);

COMMENT ON TABLE users IS 'Пользователи системы';
COMMENT ON COLUMN users.id IS 'Внутренний ID (6-значный)';
COMMENT ON COLUMN users.specialization_id IS 'Специализация (роль)';
COMMENT ON COLUMN users.primary_specialty_id IS 'Основная медицинская специальность';
COMMENT ON COLUMN users.secondary_specialty_id IS 'Дополнительная медицинская специальность';
COMMENT ON COLUMN users.practice_condition_id IS 'Условия ведения практики (только для Врача)';
COMMENT ON COLUMN users.country IS 'Страна';
COMMENT ON COLUMN users.email IS 'E-mail (логин)';
COMMENT ON COLUMN users.password_hash IS 'Хеш пароля (bcrypt/argon2)';
COMMENT ON COLUMN users.gender IS 'Пол';
COMMENT ON COLUMN users.birth_date IS 'Дата рождения';
COMMENT ON COLUMN users.work_start_year IS 'С какого года работает в медицине';
COMMENT ON COLUMN users.first_name IS 'Имя';
COMMENT ON COLUMN users.last_name IS 'Фамилия';
COMMENT ON COLUMN users.middle_name IS 'Отчество';
COMMENT ON COLUMN users.phone IS 'Номер телефона';
COMMENT ON COLUMN users.city IS 'Город проживания';
COMMENT ON COLUMN users.workplace IS 'Название места работы';
COMMENT ON COLUMN users.utm_campaign IS 'Метка рекламной кампании';
COMMENT ON COLUMN users.utm_source IS 'Источник перехода';
COMMENT ON COLUMN users.cookie_id IS 'Cookie ID для отслеживания';
COMMENT ON COLUMN users.status IS 'Статус пользователя';
COMMENT ON COLUMN users.registered_at IS 'Дата регистрации';
COMMENT ON COLUMN users.updated_at IS 'Дата последнего обновления';

-- email уже покрыт UNIQUE-индексом, отдельный idx_users_email не создаётся
CREATE INDEX idx_users_specialization ON users (specialization_id);
CREATE INDEX idx_users_status ON users (status);
CREATE INDEX idx_users_registered_at ON users (registered_at);
CREATE INDEX idx_users_cookie_id ON users (cookie_id);

-- Case-insensitive email lookup (login uses lower(email) = lower(:email))
CREATE INDEX idx_users_email_lower ON users (lower(email));

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

