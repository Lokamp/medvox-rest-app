-- ============================================================================
-- SMTP-шлюзы для отправки писем
-- Пароль шифруется через AES-256-CBC ключом из .env (SMTP_ENCRYPTION_KEY)
-- ============================================================================
CREATE TABLE smtp_gates (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title               VARCHAR(100) NOT NULL,
    server              VARCHAR(255) NOT NULL DEFAULT '',
    login               VARCHAR(255) NOT NULL DEFAULT '',
    password_encrypted  TEXT NOT NULL,
    port                SMALLINT NOT NULL DEFAULT 465,
    security            smtp_security_type NOT NULL DEFAULT 'ssl',
    from_email          VARCHAR(255) NOT NULL DEFAULT '',
    from_name           VARCHAR(255) NOT NULL DEFAULT '',
    is_active           BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NULL
);

COMMENT ON TABLE smtp_gates IS 'SMTP-шлюзы';
COMMENT ON COLUMN smtp_gates.title IS 'Название шлюза (SMTP 1, SMTP 2)';
COMMENT ON COLUMN smtp_gates.server IS 'SMTP-сервер';
COMMENT ON COLUMN smtp_gates.login IS 'Логин';
COMMENT ON COLUMN smtp_gates.password_encrypted IS 'Пароль (AES-256-CBC, base64)';
COMMENT ON COLUMN smtp_gates.port IS 'Порт';
COMMENT ON COLUMN smtp_gates.security IS 'Тип шифрования';
COMMENT ON COLUMN smtp_gates.from_email IS 'Адрес отправителя';
COMMENT ON COLUMN smtp_gates.from_name IS 'Имя отправителя';
COMMENT ON COLUMN smtp_gates.is_active IS 'Шлюз активен';

CREATE TRIGGER trg_smtp_gates_updated_at
    BEFORE UPDATE ON smtp_gates
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();

