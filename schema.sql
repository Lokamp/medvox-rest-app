COMMENT ON COLUMN money_transactions.status IS 'Статус';
COMMENT ON COLUMN money_transactions.payment_method IS 'Способ выплаты';
COMMENT ON COLUMN money_transactions.earned_at IS 'Дата начисления';
COMMENT ON COLUMN money_transactions.paid_at IS 'Дата фактической выплаты';

CREATE INDEX idx_money_user_id ON money_transactions (user_id);
